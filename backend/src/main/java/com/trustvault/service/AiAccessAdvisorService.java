package com.trustvault.service;

import com.trustvault.dto.AiAccessSuggestionDto;
import com.trustvault.entity.*;
import com.trustvault.exception.ResourceNotFoundException;
import com.trustvault.repository.DocumentGrantRepository;
import com.trustvault.repository.DocumentRepository;
import com.trustvault.repository.UserRepository;
import com.trustvault.security.SecurityUtils;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.UUID;

@Service
public class AiAccessAdvisorService {

    private final DocumentRepository documentRepository;
    private final DocumentGrantRepository grantRepository;
    private final UserRepository userRepository;
    private final DocumentAuthorizationService authorizationService;
    private final AuditService auditService;

    public AiAccessAdvisorService(DocumentRepository documentRepository,
                                  DocumentGrantRepository grantRepository,
                                  UserRepository userRepository,
                                  DocumentAuthorizationService authorizationService,
                                  AuditService auditService) {
        this.documentRepository = documentRepository;
        this.grantRepository = grantRepository;
        this.userRepository = userRepository;
        this.authorizationService = authorizationService;
        this.auditService = auditService;
    }

    /**
     * Generates a security-conscious, least-privilege access suggestion for a document.
     * The machine NEVER widens access autonomously. An authorized owner must review and confirm.
     */
    @Transactional
    public AiAccessSuggestionDto generateAccessSuggestion(UUID documentId, User currentUser) {
        Document document = documentRepository.findByIdAndIsDeletedFalse(documentId)
                .orElseThrow(() -> new ResourceNotFoundException("Document not found"));

        // Enforce strict owner check: only document owner can request access suggestions
        authorizationService.checkCanManageGrants(currentUser, document);

        String category = document.getCategory() != null ? document.getCategory() : "General";
        String catLower = category.toLowerCase(Locale.ROOT);
        String nameLower = document.getOriginalDisplayName().toLowerCase(Locale.ROOT);

        // Find candidate active users who are not the owner
        List<User> candidateUsers = userRepository.findAll().stream()
                .filter(u -> !u.getId().equals(currentUser.getId()))
                .filter(u -> u.getStatus() == UserStatus.ACTIVE)
                .toList();

        // Prefer users who do not already have an active grant
        Optional<User> ungrantedCandidate = candidateUsers.stream()
                .filter(u -> !grantRepository.hasActiveGrant(document.getId(), u.getId()))
                .findFirst();

        User selectedTarget = ungrantedCandidate.orElse(
                candidateUsers.isEmpty() ? null : candidateUsers.get(0)
        );

        String targetEmail = selectedTarget != null ? selectedTarget.getEmail() : "viewer@trustvault.local";
        GrantPermission suggestedPermission = GrantPermission.READ;
        String confidence = "HIGH";
        String rationale;

        if (catLower.contains("finance") || nameLower.contains("salary") || nameLower.contains("audit") || nameLower.contains("tax")) {
            rationale = "Finance & Audit classification detected. Recommended recipient is restricted to READ (view & download) following strict principle of least privilege. Write and edit privileges are withheld to maintain audit trail integrity.";
        } else if (catLower.contains("legal") || nameLower.contains("contract") || nameLower.contains("agreement")) {
            rationale = "Legal document classification detected. External review requires READ access. Edit permissions should remain restricted to contract owners.";
        } else if (catLower.contains("security")) {
            rationale = "Security architecture classification detected. Recommended for technical peer review with READ permissions. Least-privilege baseline enforced.";
        } else if (catLower.contains("confidential")) {
            rationale = "Confidential document classification detected. Strictly limited to READ-only access. Periodic access review and prompt revocation upon project conclusion are recommended.";
        } else {
            rationale = "Standard collaboration recommendation. Applying least-privilege baseline with READ access. Edit privileges must be explicitly granted if collaborative authorship is required.";
            confidence = "MEDIUM";
        }

        String notice = "SECURITY NOTICE: This recommendation was generated by the TrustVault AI Access Advisor under least-privilege rules. The system will NEVER grant access automatically. A human document owner must explicitly confirm or adjust this suggestion.";

        // Record the recommendation generation into the tamper-evident audit ledger
        auditService.recordEvent(
                currentUser.getId(),
                AuditAction.AI_ACCESS_SUGGESTION,
                document.getId(),
                selectedTarget != null ? selectedTarget.getId() : null,
                AuditOutcome.SUCCESS,
                SecurityUtils.getCorrelationId(),
                String.format("AI Advisor generated sharing recommendation for '%s': suggested %s with %s permission (Confidence: %s, Rationale: %s)",
                        document.getOriginalDisplayName(), targetEmail, suggestedPermission, confidence, rationale)
        );

        return new AiAccessSuggestionDto(
                document.getId(),
                document.getOriginalDisplayName(),
                category,
                targetEmail,
                suggestedPermission,
                rationale,
                confidence,
                notice
        );
    }
}
